const STRINGS: Record<Locale, Record<string, string>> = { en: EN, hi: HI };

let current: Locale = 'en';
export function getLocale(): Locale { return current; }
export function setLocale(locale: Locale) { current = locale; }

/** Returns "Today" or "आज" — also picks up the active locale automatically. */
export function t(key: string, vars?: Record<string, string | number>): string {
  const dict = STRINGS[current] || EN;
  let raw = dict[key] ?? EN[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      raw = raw.replace(new RegExp(`{{\\s*${k}\\s*}}`, 'g'), String(v));
    }
  }
  return raw;
}
